--Рост числа образцов по годам
SELECT 
    YEAR(created) AS year,
    COUNT(*) AS cnt
FROM obrs
WHERE deleted = 0
GROUP BY year
ORDER BY year;

--Нагрузка по лабораториям за все время 
SELECT 
    CASE HEX(p.name)
        WHEN 'D2EEEAF12E2DE1E8EEEB2E' THEN 'Токс.-биол.'
        WHEN 'D5E8EC2E' THEN 'Хим.'
        WHEN 'D0E0E42E' THEN 'Рад.'
        WHEN 'C1E0EA2E' THEN 'Бак.'
        WHEN 'CFD6D0' THEN 'ПЦР'
        ELSE CONCAT('Неизвестно (', HEX(p.name), ')')
    END AS lab_name,
    COUNT(*) AS results_cnt
FROM results r
JOIN podrs p ON p.id = r.podr_id
WHERE r.deleted = 0
GROUP BY HEX(p.name)
ORDER BY results_cnt DESC;

--По типам исследований за все время 
SELECT 
    YEAR(o.created) AS yr,
    CASE HEX(ot.name)
        WHEN 'EFF0EEE4F3EAF2FB' THEN 'продукты'
        WHEN 'EFF0EEE4F3EAF2FB2028F0E5F1F2EEF0E0ED29' THEN 'продукты (ресторан)'
        WHEN 'E2EEE4E02028E8E720F1E5F2E829' THEN 'вода (из сети)'
        WHEN 'E2EEE4E02028CDC520E8E720F1E5F2E829' THEN 'вода (НЕ из сети)'
        WHEN 'E2EEE7E4F3F5' THEN 'воздух'
        WHEN 'F1ECFBE2FB' THEN 'смывы'
        WHEN 'ECFFF1EE' THEN 'мясо'
        WHEN 'EAEEF1ECE5F2E8EAE0' THEN 'косметика'
        ELSE CONCAT('Неизвестно (', HEX(ot.name), ')')
    END AS obr_type,
    COUNT(*) AS cnt
FROM obrs o
JOIN obr_types ot ON ot.id = o.obr_type_id
WHERE o.deleted = 0
GROUP BY 1, HEX(ot.name)
ORDER BY 1, cnt DESC;

